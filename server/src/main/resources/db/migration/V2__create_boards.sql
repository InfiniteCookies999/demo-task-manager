CREATE TABLE boards (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id                        BIGINT NOT NULL,
    background_type                 VARCHAR(255) NOT NULL,
    background_solid_color          VARCHAR(7) NOT NULL,
    background_gradient_start_color VARCHAR(7) NOT NULL,
    background_gradient_end_color   VARCHAR(7) NOT NULL,

    CONSTRAINT fk_boards_owner
        FOREIGN KEY (owner_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_boards_owner
        UNIQUE (owner_id)
);
